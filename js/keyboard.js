/**
 * Stores the current keyboard input state.
 *
 * Contains the keys used for character movement
 * and actions.
 */
class Keyboard {
  /** Indicates whether the left key is pressed. */
  LEFT = false;

  /** Indicates whether the right key is pressed. */
  RIGHT = false;

  /** Indicates whether the up key is pressed. */
  UP = false;

  /** Indicates whether the space key is pressed. */
  SPACE = false;

  /** Indicates whether the throw key is pressed. */
  D = false;
}
